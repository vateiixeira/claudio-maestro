"""Loading a saved conversation (`get_session_messages`) into the ConversationBuilder."""

from history_fakes import assistant_entry, user_entry

from claudio_maestro.conversation import ConversationBuilder


def test_text_tool_with_result_and_tool_without_result():
    entries = [
        user_entry("crie o arquivo"),
        assistant_entry({"type": "thinking", "thinking": "pensando", "signature": "x"}, "m1"),
        assistant_entry({"type": "text", "text": "Vou criar."}, "m1"),
        assistant_entry(
            {"type": "tool_use", "id": "t1", "name": "Write", "input": {"file_path": "a"}}, "m1"
        ),
        user_entry([{"type": "tool_result", "tool_use_id": "t1", "content": "ok"}]),
        assistant_entry({"type": "text", "text": "Pronto."}, "m2"),
        assistant_entry({"type": "tool_use", "id": "t2", "name": "Bash", "input": {}}, "m2"),
    ]
    builder = ConversationBuilder()

    builder.load_history(entries)

    items = builder.snapshot()
    assert [i["type"] for i in items] == ["user", "thinking", "text", "tool", "text", "tool"]
    assert items[0]["text"] == "crie o arquivo"
    assert items[1]["text"] == "pensando" and items[1]["streaming"] is False
    assert items[2]["id"] == "m1:1"
    tool = items[3]
    assert tool["tool_use_id"] == "t1"
    assert tool["result"] == {"content": "ok", "is_error": None, "details": None}
    assert tool["streaming"] is False
    assert items[5]["result"] is None and items[5]["streaming"] is False
    assert len({i["id"] for i in items}) == len(items)


