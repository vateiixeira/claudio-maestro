from claudio_maestro.conversation import cap_content, slim_details  # noqa: E402


def test_edit_details_keep_patch_only():
    details = {"filePath": "a.py", "structuredPatch": [{"lines": ["+x"]}], "type": "update",
               "userModified": False, "originalFile": "x" * 10, "content": "y",
               "oldString": "o", "newString": "n"}
    for name in ("Edit", "MultiEdit", "Write"):
        assert slim_details(name, details) == {
            "filePath": "a.py", "structuredPatch": [{"lines": ["+x"]}], "type": "update",
            "userModified": False,
        }


def test_read_details_keep_path_and_counts():
    details = {"type": "text", "file": {"filePath": "a.py", "content": "abc", "numLines": 3,
                                        "startLine": 1, "totalLines": 9}}
    assert slim_details("Read", details) == {
        "type": "text", "file": {"filePath": "a.py", "numLines": 3, "startLine": 1, "totalLines": 9}
    }


def test_other_details_cut_long_strings():
    details = {"stdout": "a" * 20_005, "nested": [{"s": "b" * 10}], "n": 1}
    slim = slim_details("Bash", details)
    assert slim["stdout"] == "a" * 20_000 + "…[cortado 5 caracteres]"
    assert slim["nested"] == [{"s": "b" * 10}] and slim["n"] == 1
    assert slim_details("Bash", None) is None
    assert slim_details("Bash", "texto") == "texto"


def test_result_content_is_capped():
    assert cap_content("c" * 200_010) == "c" * 200_000 + "…[cortado 10 caracteres]"
    capped = cap_content([{"type": "text", "text": "d" * 200_001}])
    assert capped[0]["text"].endswith("…[cortado 1 caracteres]")


def test_limits_apply_to_history_and_live():
    from claude_agent_sdk import ToolResultBlock, ToolUseBlock, UserMessage

    raw = {"t1": {"content": "e" * 200_003, "is_error": False,
                  "details": {"filePath": "f", "originalFile": "big"}}}
    builder = ConversationBuilder()
    builder.load_history([assistant_entry(tool_use("t1", "Edit"), "m1")], raw)
    result = builder.snapshot()[0]["result"]
    assert result["details"] == {"filePath": "f"}
    assert len(result["content"]) < 200_100

    live = ConversationBuilder()
    live._apply_block(ToolUseBlock(id="t2", name="Edit", input={}), "m:0", None)
    live.handle(UserMessage(
        content=[ToolResultBlock(tool_use_id="t2", content="ok")],
        tool_use_result={"filePath": "f", "originalFile": "big", "structuredPatch": []},
    ))
    assert live.snapshot()[0]["result"]["details"] == {"filePath": "f", "structuredPatch": []}
