def test_user_images_and_documents_become_light_markers():
    builder = ConversationBuilder()
    builder.load_history([
        user_entry([
            {"type": "image", "source": {"type": "base64", "media_type": "image/png",
                                         "data": "A" * 400}},
            {"type": "document", "source": {"type": "base64", "media_type": "application/pdf",
                                            "data": "B" * 40}},
        ]),
    ])
    items = builder.snapshot()
    assert len(items) == 1 and items[0]["type"] == "user"
    assert items[0]["text"] == ""
    assert items[0]["images"] == [
        {"type": "image", "media_type": "image/png", "size": 300},
        {"type": "document", "media_type": "application/pdf", "size": 30},
    ]
    assert "AAAA" not in str(items)


def test_tool_result_images_are_omitted():
    screenshot = {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg",
                                              "data": "Z" * 1000}}
    builder = ConversationBuilder()
    builder.load_history(
        [
            assistant_entry(tool_use("t1", "Screenshot"), "m1"),
            user_entry([{"type": "tool_result", "tool_use_id": "t1",
                         "content": [{"type": "text", "text": "ok"}, screenshot]}]),
            assistant_entry(tool_use("t2", "Screenshot"), "m1"),
        ],
        {"t2": {"content": [screenshot], "is_error": False, "details": None}},
    )
    tools = builder.snapshot()
    assert tools[0]["result"]["content"] == [
        {"type": "text", "text": "ok"},
        {"type": "image", "omitted": True, "media_type": "image/jpeg"},
    ]
    assert tools[1]["result"]["content"] == [
        {"type": "image", "omitted": True, "media_type": "image/jpeg"}
    ]
    assert "ZZZ" not in str(tools)


def test_empty_and_redacted_thinking_are_dropped():
    builder = ConversationBuilder()
